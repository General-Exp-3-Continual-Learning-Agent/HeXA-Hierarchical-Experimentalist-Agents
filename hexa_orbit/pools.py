"""Maze instance pools: ORBIT's seed derivation, plus the identity D6 requires.

Three things this module is responsible for, in order of how easy they are to get
wrong:

**1. Deriving the same seeds ORBIT does.** ORBIT builds an instance pool by
hashing the task config and drawing from a seeded generator. The scheme is
transcribed in :func:`task_specific_seed` and :func:`pool_seeds` rather than
imported, because the two places ORBIT implements it
(``data/prepare_gem_data.py:146-206`` and ``scripts/eval/openai.py:300-361``) both
live behind module-level ``rllm``/``omegaconf`` imports we are deliberately not
installing (D4). The transcription is four lines of hashing and one RNG call, and
``hexa_orbit.tests.test_pools`` pins the derived values so a drift in either
direction is caught.

**2. Not perturbing the hash.** The hash covers *the entire task config* -- change
``shapes``, ``num_numbers``, or ``total_step_cap`` and every seed in both pools
moves (RECON §2). This collides with D3, which runs Maze at ``total_step_cap=27``
while ORBIT's published eval config says 45. Resolving that collision is the
central design constraint here: **seeds are derived from the published config
verbatim; the runtime step cap is a separate argument that never reaches the
hash.** :func:`published_maze_config` returns the config as checked in and is the
only thing :func:`pool_seeds` ever hashes. Anything that wants to change how an
instance is *run* must go through :mod:`hexa_orbit.adapter`, not through here.

**3. Instance identity that survives the seed walk.** ``MazeEnvAdapter.reset``
increments the seed until the maze satisfies the shortest-path filter
(``envs/maze_env_adapter.py:411-421``), so the seed you ask for is usually not the
seed you get: 165 of ORBIT's 256 eval seeds resolve elsewhere, and distinct
dataset seeds collide onto identical mazes (RECON §1). Per D6, identity is the
resolved seed and a hash of the maze layout -- never the dataset seed. Both are
stamped onto every :class:`MazeInstanceSpec` at construction.

Everything here is pure and deterministic. No LLM, no environment stepping.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Iterable, Mapping, Sequence

import numpy as np
import yaml

from .orbit_bridge import install_orbit_on_path, orbit_repo_root

#: ORBIT's default global seed: ``--seed 42`` in ``scripts/eval/openai.sh``, and
#: the ``seed: int = 42`` default of ``prepare_multi_task_gem_data``.
DEFAULT_GLOBAL_SEED = 42

#: Size parameters excluded from the config hash, matching ORBIT's own exclusion
#: (``prepare_gem_data.py:151-154``). Because both are dropped, the train and
#: eval pools hash the *same* base value and are separated only by the ``* 2``
#: below -- which is the entire mechanism keeping them disjoint (RECON §2).
_SIZE_KEYS = ("train_size", "test_size")

#: ORBIT's published eval pool size for Maze (``configs/eval_config.yaml``).
EVAL_POOL_SIZE = 256

#: Upper bound of ORBIT's seed draw, ``integers(0, 1_000_000, size=n)``.
_SEED_HI = 1_000_000


def task_specific_seed(task_cfg: Mapping[str, Any], global_seed: int = DEFAULT_GLOBAL_SEED) -> int:
    """SHA-256 config hash → pool RNG seed. Transcribed from ORBIT.

    From ``data/prepare_gem_data.py:146-180`` (identical to
    ``scripts/eval/openai.py:_get_task_specific_seed``). The ``str(sorted(...))``
    is load-bearing and reproduced exactly: the hash is over Python's *repr* of a
    sorted item list, so it is sensitive to value types as well as values --
    ``9`` and ``9.0`` hash differently, as do a ``list`` and a ``tuple``. Configs
    must therefore come from ``yaml.safe_load`` of ORBIT's own file, not from a
    hand-written dict (see :func:`published_maze_config`).
    """
    params = {k: v for k, v in task_cfg.items() if k not in _SIZE_KEYS}
    param_str = str(sorted(params.items())) + str(global_seed)
    digest = hashlib.sha256(param_str.encode()).digest()
    return int.from_bytes(digest[:8], byteorder="big") % (2**31)


def pool_seeds(
    task_cfg: Mapping[str, Any],
    size: int,
    *,
    is_train: bool,
    global_seed: int = DEFAULT_GLOBAL_SEED,
) -> list[int]:
    """The dataset seeds ORBIT would draw for this config, split and size.

    ``is_train`` doubles the RNG seed (``prepare_gem_data.py:201``). That single
    ``* 2`` is what separates train from eval; measured overlap between a
    512-train and 256-eval draw is zero for Maze, at both the dataset-seed and
    resolved-seed level (RECON §2).

    Note ORBIT never actually drew a *train* pool for Maze -- Maze appears only
    under ``val_tasks`` (RECON §0b) -- so the train pool is ours, generated by
    ORBIT's scheme rather than reproduced from a published artifact.
    """
    if size < 1:
        raise ValueError(f"size must be >= 1, got {size}")
    seed = task_specific_seed(task_cfg, global_seed)
    if is_train:
        seed *= 2
    rng = np.random.default_rng(seed)
    return rng.integers(0, _SEED_HI, size=size).tolist()


def published_maze_config(config_name: str = "eval_config.yaml") -> dict[str, Any]:
    """ORBIT's Maze task config, loaded verbatim from its checked-in YAML.

    Loaded rather than transcribed for the reason given in
    :func:`task_specific_seed`: the hash depends on value *types*, so YAML is the
    only safe source. Returned unmodified -- in particular ``total_step_cap: 45``
    is preserved even though D3 runs at 27, because mutating it here would redraw
    every seed in both pools and silently replace ORBIT's published 256-instance
    eval set with a different one.

    ``configs/eval_config.yaml`` is the default because it is what
    ``scripts/eval/openai.sh`` uses, and therefore what most likely produced
    ORBIT's Table 2 Maze numbers (D3).
    """
    install_orbit_on_path()
    path = Path(orbit_repo_root()) / "configs" / config_name
    with path.open(encoding="utf-8") as fh:
        config = yaml.safe_load(fh)
    for task in config.get("val_tasks") or ():
        if task.get("env_id") == "maze":
            return dict(task)
    raise KeyError(f"No 'maze' entry under val_tasks in {path}")


def resolve_seed(
    generator: Any,
    seed: int,
    *,
    min_len: int,
    max_len: int,
    max_tries: int = 1000,
) -> tuple[int, np.ndarray, tuple[int, int], int]:
    """Walk the seed forward until the maze passes the shortest-path filter.

    Transcribed from ``MazeEnvAdapter.reset`` (``envs/maze_env_adapter.py:411-421``)
    because the adapter discards the walked seed: it mutates a local and stores
    only ``map`` / ``init_position`` / ``shortest_path_len``, so the resolved seed
    is unrecoverable from the object afterwards. D6 wants it recorded, hence this
    reimplementation -- and because it *is* a reimplementation of load-bearing
    filter logic, ``test_pools.test_resolve_seed_matches_adapter`` asserts the
    resulting map equals what the adapter itself produces.

    Returns ``(resolved_seed, maze, init_position, shortest_path_len)``.
    """
    current = int(seed)
    for _ in range(max_tries):
        maze, init_position, path_len = generator.generate(current)
        if min_len <= path_len <= max_len:
            return current, maze, init_position, path_len
        current += 1
    raise ValueError(
        f"No maze with shortest path in [{min_len}, {max_len}] within "
        f"{max_tries} seeds from {seed}"
    )


def maze_hash(maze: np.ndarray, init_position: tuple[int, int]) -> str:
    """Stable content hash of one maze instance -- D6's primary identity.

    Covers the grid (walls, paths, and the goal cell, which ``generate`` marks as
    ``-1`` in the array it returns) *and* the start position. The start must be
    included: two instances can share a layout while starting the agent in
    different cells, which makes them different problems.

    ``int8`` normalises dtype so the hash does not depend on numpy's platform
    integer width; values are only ``{-1, 0, 1}``. Shape is folded in so a
    reshape cannot collide.
    """
    grid = np.ascontiguousarray(maze, dtype=np.int8)
    payload = b"|".join(
        (
            b"maze-v1",
            repr(grid.shape).encode(),
            grid.tobytes(),
            repr(tuple(int(v) for v in init_position)).encode(),
        )
    )
    return hashlib.sha256(payload).hexdigest()


@dataclass(frozen=True)
class MazeInstanceSpec:
    """One Maze instance, fully identified before any environment is stepped.

    ``dataset_seed`` is what ORBIT's pool draw produced and what must be passed
    to ``MazeEnvAdapter.reset`` to reproduce this instance. It is explicitly
    **not** the identity: use :attr:`instance_id` (D6). Both are kept because the
    dataset seed is the only way to *construct* the instance, while the hash is
    the only sound way to *compare* instances.
    """

    dataset_seed: int
    resolved_seed: int
    maze_hash: str
    shortest_path_len: int
    init_position: tuple[int, int]
    shape: tuple[int, int]
    split: str

    @property
    def instance_id(self) -> str:
        """Stable identity: the layout hash, abbreviated for logs."""
        return self.maze_hash[:16]

    @property
    def seed_was_walked(self) -> bool:
        """True when the shortest-path filter moved the seed (165/256 on eval)."""
        return self.resolved_seed != self.dataset_seed

    def to_dict(self) -> dict[str, Any]:
        return {
            "instance_id": self.instance_id,
            "dataset_seed": self.dataset_seed,
            "resolved_seed": self.resolved_seed,
            "maze_hash": self.maze_hash,
            "shortest_path_len": self.shortest_path_len,
            "init_position": list(self.init_position),
            "shape": list(self.shape),
            "split": self.split,
            "seed_was_walked": self.seed_was_walked,
        }


def build_pool(
    task_cfg: Mapping[str, Any],
    size: int,
    *,
    is_train: bool,
    global_seed: int = DEFAULT_GLOBAL_SEED,
) -> list[MazeInstanceSpec]:
    """Materialise one pool, resolving and hashing every instance.

    Runs the generator once per instance (plus once per rejected seed in the
    walk), which is milliseconds each and involves no model calls.
    """
    install_orbit_on_path()
    from envs.maze_env_adapter import MazeGenerator  # noqa: PLC0415

    shapes = [tuple(s) for s in task_cfg["shapes"]]
    min_len = int(task_cfg["shortest_path_min_length"])
    max_len = int(task_cfg["shortest_path_max_length"])
    generator = MazeGenerator(shapes)
    split = "train" if is_train else "eval"

    specs: list[MazeInstanceSpec] = []
    for dataset_seed in pool_seeds(task_cfg, size, is_train=is_train, global_seed=global_seed):
        resolved, maze, init_position, path_len = resolve_seed(
            generator, dataset_seed, min_len=min_len, max_len=max_len
        )
        specs.append(
            MazeInstanceSpec(
                dataset_seed=int(dataset_seed),
                resolved_seed=int(resolved),
                maze_hash=maze_hash(maze, init_position),
                shortest_path_len=int(path_len),
                init_position=(int(init_position[0]), int(init_position[1])),
                shape=(int(maze.shape[0]), int(maze.shape[1])),
                split=split,
            )
        )
    return specs


# ── Disjointness and leakage (D6, and the leakage-split requirement) ──────

class PoolContamination(ValueError):
    """Raised when train and eval pools share a dataset or resolved seed."""


def assert_disjoint(
    train: Sequence[MazeInstanceSpec], eval_: Sequence[MazeInstanceSpec]
) -> None:
    """Assert the pools share no dataset seed and no resolved seed.

    Layout overlap is *not* checked here, because it is expected and tolerated --
    18% of eval mazes are byte-identical to a train maze (RECON §0c, D1). That is
    what :func:`leakage_split` is for. Seed overlap, by contrast, should be
    exactly zero and a nonzero count means the derivation broke.
    """
    for field_name in ("dataset_seed", "resolved_seed"):
        shared = {getattr(s, field_name) for s in train} & {
            getattr(s, field_name) for s in eval_
        }
        if shared:
            raise PoolContamination(
                f"{len(shared)} {field_name}(s) appear in both pools, expected 0; "
                f"examples: {sorted(shared)[:5]}"
            )


def leakage_split(
    eval_: Sequence[MazeInstanceSpec], train: Sequence[MazeInstanceSpec]
) -> dict[str, list[MazeInstanceSpec]]:
    """Partition eval instances into ``"leaked"`` and ``"clean"``.

    Leaked = the exact layout (and start) occurs somewhere in the train pool, so
    a bank could have seen this specific maze during evolution and could carry a
    memorised route rather than a general strategy. Every headline metric is
    reported over both partitions separately -- the requirement DECISIONS.md adds
    after D1, and the reason it must exist before the Phase 2 baseline runs
    rather than being retrofitted afterwards.
    """
    train_hashes = {s.maze_hash for s in train}
    leaked = [s for s in eval_ if s.maze_hash in train_hashes]
    clean = [s for s in eval_ if s.maze_hash not in train_hashes]
    return {"leaked": leaked, "clean": clean}


def pool_summary(
    train: Sequence[MazeInstanceSpec], eval_: Sequence[MazeInstanceSpec]
) -> dict[str, Any]:
    """Auditable one-shot description of a pool pair, for the run manifest."""
    split = leakage_split(eval_, train)
    return {
        "n_train": len(train),
        "n_eval": len(eval_),
        "distinct_train_mazes": len({s.maze_hash for s in train}),
        "distinct_eval_mazes": len({s.maze_hash for s in eval_}),
        "eval_seeds_walked": sum(1 for s in eval_ if s.seed_was_walked),
        "n_eval_leaked": len(split["leaked"]),
        "n_eval_clean": len(split["clean"]),
        "leaked_fraction": len(split["leaked"]) / len(eval_) if eval_ else 0.0,
        "eval_shortest_path_lens": {
            length: sum(1 for s in eval_ if s.shortest_path_len == length)
            for length in sorted({s.shortest_path_len for s in eval_})
        },
    }
